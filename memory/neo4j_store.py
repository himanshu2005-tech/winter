    def find_person_nodes(self, query, limit=6):
        """Existing graph nodes a name could refer to: exact first, then people.

        Used to hang a face on the node that already exists for someone (their
        contact, with the phone number) instead of creating a second one. A
        loose match counts only when the node is a person or carries contact
        facts, so "Madhu" cannot attach to an unrelated place or topic.
        """
        value = str(query or "").strip()
        if not value:
            return []
        return self.query(
            """
            MATCH (e:Entity)
            WHERE e.key=$key OR e.norm_key=$norm OR toLower(e.name)=$lower
               OR any(a IN coalesce(e.aliases,[]) WHERE toLower(a)=$lower)
               OR (size($lower) >= 3 AND (' ' + toLower(e.name)) CONTAINS (' ' + $lower))
            OPTIONAL MATCH (e)-[f:FACT]->()
            WHERE f.predicate IN ['HAS_PHONE','PRIMARY_EMAIL','HAS_CONTACT']
              AND f.valid_to IS NULL
            WITH e, count(f) AS contact_facts,
                 (e.key=$key OR e.norm_key=$norm OR toLower(e.name)=$lower
                  OR any(a IN coalesce(e.aliases,[]) WHERE toLower(a)=$lower)) AS exact
            WHERE exact OR e.entity_type='Person' OR contact_facts > 0
            RETURN e.name AS name, contact_facts, exact
            ORDER BY exact DESC, contact_facts DESC, size(e.name)
            LIMIT $limit
            """,
            key=_slug(value), norm=_norm_key(value), lower=value.casefold(),
            limit=int(limit),
        )

