    def search_facts(self, query, limit=12, entity_keys=None, predicates=None,
                     locators_only=False):
        """Rank current facts for a query.

        The router already identifies the entities and predicates a turn is
        about, but those used to be flattened into the keyword string and
        matched as substrings. Here they anchor the search structurally, which
        the Entity and FACT indexes can serve, while token overlap still
        contributes so unanchored queries keep working.
        """
        tokens = fact_query_tokens(query)
        keys, norms = [], []
        for value in entity_keys or []:
            text = str(value or "").strip()
            if text:
                keys.append(_slug(text))
                norms.append(_norm_key(text))
        preds = expand_query_predicates(predicates)
        if not tokens and not keys and not preds:
            return []
        rows = self.query(
            """
            MATCH (s:Entity)-[r:FACT]->(o:Entity)
            WHERE r.valid_to IS NULL
              AND (NOT $locators_only OR o.name STARTS WITH 'https://'
                   OR o.name STARTS WITH 'http://'
                   OR any(word IN ['URL','LINK','WEBSITE','ENDPOINT','REPOSITORY']
                          WHERE r.predicate CONTAINS word))
            WITH s,r,o,
              [token IN $tokens WHERE
                toLower(s.name) CONTAINS token OR toLower(o.name) CONTAINS token OR
                toLower(r.predicate) CONTAINS token] AS matched,
              (s.key IN $keys OR o.key IN $keys OR
               coalesce(s.norm_key,'') IN $norms OR coalesce(o.norm_key,'') IN $norms) AS anchored,
              (r.predicate IN $preds) AS predicate_hit
            WHERE CASE
              // A routed predicate is a structural constraint, not a mild
              // keyword hint. Otherwise every fact about Himanshu ties on the
              // entity anchor and crowds out the requested relationship.
              WHEN size($preds)>0 AND size($keys)>0 THEN predicate_hit AND anchored
              WHEN size($preds)>0 THEN predicate_hit
              WHEN size($keys)>0 THEN anchored OR size(matched)>0
              ELSE size(matched)>0
            END
            WITH s,r,o,matched,
              size(matched)*3.0
              + (CASE WHEN anchored THEN 5.0 ELSE 0.0 END)
              + (CASE WHEN predicate_hit THEN 4.0 ELSE 0.0 END)
              + coalesce(r.confidence,0.5)
              + (coalesce(r.authority,50) / 100.0) * 2.0
              + CASE coalesce(r.fact_class,'explicit_user_fact')
                  WHEN 'explicit_user_fact' THEN 2.0
                  WHEN 'self_reported_pattern' THEN 1.5
                  WHEN 'external_observation' THEN 0.5
                  ELSE 0.0 END
              // Repeated connector syncs are not independent evidence.  A
              // contact imported 80 times must not outrank a user-stated
              // relationship merely because the sync job saw it repeatedly.
              + log(1.0 + CASE
                  WHEN coalesce(r.mention_count,1) > 3 THEN 3
                  ELSE coalesce(r.mention_count,1) END) AS score
            RETURN s.name AS subject,r.predicate AS predicate,o.name AS object,
                   coalesce(r.fact_id,r.id) AS fact_id,
                   coalesce(r.fact_class,'explicit_user_fact') AS fact_class,
                   coalesce(r.evidence_type,'legacy') AS evidence_type,
                   coalesce(r.authority,50) AS authority,
                   coalesce(r.confidence,1.0) AS confidence,r.source_id AS source_id,
                   coalesce(r.sensitivity,'private') AS sensitivity,
                   coalesce(r.autonomy_eligible,false) AS autonomy_eligible,
                   coalesce(r.autonomy_scope,'advisory') AS autonomy_scope,
                   coalesce(r.confirmation_required,false) AS confirmation_required,
                   coalesce(r.review_status,'accepted') AS review_status,
                   coalesce(r.claim_key,s.key+':'+r.predicate) AS claim_key,
                   r.valid_from AS valid_from,r.valid_to AS valid_to,
                   properties(r).supersedes_fact_id AS supersedes_fact_id,
                   properties(r).superseded_by_fact_id AS superseded_by_fact_id,
                   properties(r).correction_reason AS correction_reason,size(matched) AS overlap,
                   score,coalesce(r.mention_count,1) AS mention_count
            ORDER BY score DESC,coalesce(r.last_seen,r.valid_from) DESC LIMIT $limit
            """,
            tokens=tokens,limit=int(limit),keys=keys,norms=norms,preds=preds,
            locators_only=bool(locators_only),
        )
        return rows

    def correct_fact(self, subject, predicate, new_object, old_object=None,
                     reason='explicit user correction', source_id='user_stated'):
        """Retirement and replacement commit together, or neither does.

        Use the normal writer within a transaction-bound facade so validation,
        canonicalization and evidence rules cannot diverge between pathways.
        """
        import copy
        from memory.fact_validation import validate_fact
        predicate = canonical_predicate(predicate)
        validate_fact(subject, predicate, new_object, 1.0, {})
        driver = self._get_driver()
        def replace(tx):
            bound = copy.copy(self)
            bound.query = lambda cypher, **params: [r.data() for r in tx.run(cypher, **params)]
            retired = bound.invalidate_fact(subject, predicate, old_object, reason)
            if old_object and not retired:
                raise ValueError('Correction target no longer matches; refresh current facts first')
            if (not old_object and predicate not in FUNCTIONAL_PREDICATES
                    and len({r.get('object') for r in retired}) > 1):
                raise ValueError('Multiple current values; provide the exact old_object to correct')
            from memory.fact_validation import SENSITIVITIES
            sensitivity = max(['private'] + [r.get('sensitivity') or 'private' for r in retired],
                              key=lambda x: SENSITIVITIES.index(x) if x in SENSITIVITIES else 3)
            result = bound.add_fact(subject, predicate, new_object, confidence=1.0,
                source_id=source_id, correction_reason=reason, authority=100,
                sensitivity=sensitivity)
            previous_ids = [r['fact_id'] for r in retired if r.get('fact_id')]
            if previous_ids:
                bound.query('''
                    MATCH (s:Entity {key:$subject})-[replacement:FACT]->(o:Entity {key:$object})
                    WHERE replacement.predicate=$predicate AND replacement.valid_to IS NULL
                    WITH s,replacement
                    MATCH (s)-[old:FACT]->()
                    WHERE coalesce(old.fact_id,old.id) IN $previous_ids
                    SET old.superseded_by_fact_id=coalesce(replacement.fact_id,replacement.id),
                        replacement.supersedes_fact_ids=$previous_ids,
                        replacement.supersedes_fact_id=CASE WHEN size($previous_ids)=1
                            THEN head($previous_ids) ELSE replacement.supersedes_fact_id END
                ''', subject=_slug(bound.canonical_name(subject)),
                    object=_slug(bound.canonical_name(new_object)), predicate=predicate,
                    previous_ids=previous_ids)
            return {'retired': len(retired), 'result': result}
        with driver.session(database=self._database()) as session:
            return session.execute_write(replace)

    def invalidate_fact(self, subject, predicate=None, object_value=None, reason=None):
        """Retire a fact by closing its validity window.

        Nothing is deleted: a retired fact stops being retrieved but its
        history survives, so a wrong correction can still be traced.
        """
        if not str(subject or '').strip() or not (predicate or object_value):
            raise ValueError('Retiring facts requires a subject and a predicate or exact object')
        predicate_norm = (
            canonical_predicate(predicate) if predicate else None
        )
        rows = self.query(
            """
            MATCH (s:Entity)-[r:FACT]->(o:Entity)
            WHERE s.key=$subject_key AND r.valid_to IS NULL
              AND ($predicate IS NULL OR r.predicate=$predicate)
              AND ($object_key IS NULL OR r.object_key=$object_key)
            SET r.valid_to=toString(datetime()), r.correction_reason=$reason
            RETURN s.name AS subject, r.predicate AS predicate, o.name AS object,
                   coalesce(r.sensitivity,'private') AS sensitivity,
                   coalesce(r.fact_id,r.id) AS fact_id
            """,
            subject_key=_slug(self.canonical_name(subject)),
            predicate=predicate_norm,
            object_key=_slug(self.canonical_name(object_value)) if object_value else None,
            reason=reason,
        )
        return rows

