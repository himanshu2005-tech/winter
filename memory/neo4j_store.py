    def explain_fact(self, subject, predicate=None, object_value=None):
        """Why VANTA believes something.

        Facts carried a bare `source_id` string with nothing to traverse, so
        "why do you think that?" was unanswerable. New facts store the exact
        sentence they were drawn from; older ones are explained by resolving
        their source against whatever produced them.
        """
        predicate_norm = canonical_predicate(predicate) if predicate else None
        rows = self.query(
            """
            MATCH (s:Entity)-[r:FACT]->(o:Entity)
            WHERE s.key=$subject_key
              AND ($predicate IS NULL OR r.predicate=$predicate)
              AND ($object_key IS NULL OR r.object_key=$object_key)
            RETURN s.name AS subject, r.predicate AS predicate, o.name AS object,
                   coalesce(r.source_id,'') AS source_id,
                   coalesce(r.evidence_quote,'') AS quote,
                   coalesce(r.evidence_ref,'') AS ref,
                   coalesce(r.rationale,'') AS rationale,
                   coalesce(r.evidence_type,'user_stated') AS evidence_type,
                   coalesce(r.fact_class,'explicit_user_fact') AS fact_class,
                   coalesce(r.review_status,'accepted') AS review_status,
                   coalesce(r.confidence,1.0) AS confidence,
                   coalesce(r.mention_count,1) AS mention_count,
                   r.valid_from AS valid_from, r.valid_to AS valid_to
            ORDER BY coalesce(r.confidence,0.0) DESC LIMIT 8
            """,
            subject_key=_slug(self.canonical_name(subject)),
            predicate=predicate_norm,
            object_key=_slug(self.canonical_name(object_value)) if object_value else None,
        )
        for row in rows:
            row["evidence"] = self._resolve_evidence(row)
        return rows

    def _resolve_evidence(self, row):
        """Turn a provenance marker into something Himanshu can check."""
        source = str(row.get("source_id") or "")
        quote = str(row.get("quote") or "").strip()
        if quote:
            # Attributing a device reading to something Himanshu said would be
            # a small lie in exactly the place provenance exists to prevent it.
            kind = str(row.get("evidence_type") or "user_stated")
            if kind == "device_measured":
                return f"measured by your devices: {quote[:240]}"
            if kind == "inferred":
                return f"inferred from: {quote[:240]}"
            return f'you said: "{quote[:240]}"'
        if row.get("rationale"):
            return f"inferred, because {row['rationale'][:240]}"
        if source.startswith("bootstrap:"):
            question = source.rsplit(":", 1)[-1]
            found = self.query(
                "MATCH (m:Memory) WHERE m.source_id=$sid OR m.id CONTAINS $q "
                "RETURN m.content AS content LIMIT 1",
                sid=source, q=question,
            )
            if found and found[0].get("content"):
                content = str(found[0]["content"])
                # Bootstrap answers are stored as JSON envelopes; show the
                # question and what he actually chose, not the wrapper.
                try:
                    import json as _json
                    parsed = _json.loads(content)
                    asked = str(parsed.get("question_text", "")).strip()
                    answer = parsed.get("raw_answer") or parsed.get("answer") or parsed.get("value")
                    if isinstance(answer, list):
                        answer = ", ".join(str(a) for a in answer)
                    answer = " ".join(str(answer or "").split())
                    if asked and answer:
                        return f'in setup you answered "{answer[:160]}" to "{asked[:120]}"'
                    if asked:
                        return f'from your setup answer to "{asked[:160]}"'
                except Exception:
                    pass
                return f'from your setup answers: "{" ".join(content.split())[:200]}"'
            return f"from your initial setup answers ({question})"
        if "contacts_sync" in source:
            return "synced from your Google Contacts"
        if (source.startswith(("remembered:", "corrected:"))
                or re.fullmatch(r"[A-F0-9]{8}_\d+", source, re.IGNORECASE)):
            turn = source.split(":", 1)[-1]
            found = self.query(
                "MATCH (t:DialogueTurn) "
                "WHERE (t.id=$id OR t.turn_id=$id) AND t.role='user' "
                "RETURN coalesce(t.content,t.user_text,t.text,'') AS text LIMIT 1",
                id=turn,
            )
            if found and found[0].get("text"):
                return f'you said: "{str(found[0]["text"])[:240]}"'
            return "you told me directly in conversation"
        if source.startswith("inference:"):
            return "inferred from other facts, and not yet confirmed"
        if source.startswith("legacy:"):
            return "imported from an earlier version of my memory"
        return f"recorded from {source}" if source else "no source was recorded"

