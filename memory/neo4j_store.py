    def health(self):
        rows = self.query("RETURN 'ok' AS status, toString(datetime()) AS server_time")
        return rows[0] if rows else {"status": "error"}

    def upsert_memory_batch(self, items):
        if not items:
            return 0
        missing = [item for item in items if not item.get("embedding")]
        if missing:
            vectors = embed_texts([item.get("content", "") for item in missing])
            for item, vector in zip(missing, vectors):
                item["embedding"] = vector
        rows = []
        for item in items:
            content = str(item.get("content", "")).strip()
            if not content:
                continue
            rows.append({
                "id": item.get("id") or _content_id("mem", item.get("kind"), item.get("source"), content),
                "kind": item.get("kind", "knowledge"),
                "topic": item.get("topic", "general"),
                "source": item.get("source", "unknown"),
                "source_id": item.get("source_id", ""),
                "title": str(item.get("title", ""))[:300],
                "content": content,
                "timestamp": str(item.get("timestamp") or _now_iso()),
                "confidence": float(item.get("confidence", 1.0)),
                "authority": int(item.get("authority", 40)),
                "content_hash": hashlib.sha256(content.encode("utf-8")).hexdigest(),
                "embedding": item["embedding"],
            })
        if rows:
            self.query(
                """
                UNWIND $rows AS row
                MERGE (m:Memory {id: row.id})
                SET m += row, m.updated_at = datetime()
                """,
                rows=rows,
            )
        return len(rows)

    def upsert_health_observations(self, import_record, observations, batch_size=1000):
        """Idempotently persist daily health measurements and provenance.

        Raw sensor samples remain in the immutable source export; the graph
        stores lossless daily metric aggregates, which are the smallest useful
        analytical unit and avoid hundreds of thousands of redundant nodes.
        """
        import_id = str(import_record["id"])
        self.query(
            """
            MERGE (i:HealthImport {id:$id})
            ON CREATE SET i.created_at=datetime()
            SET i += $props, i.updated_at=datetime()
            MERGE (p:Entity {key:'himanshu'})
            ON CREATE SET p.name='Himanshu', p.entity_type='Person',
                          p.norm_key='himanshu', p.created_at=datetime()
            MERGE (p)-[:HAS_HEALTH_IMPORT]->(i)
            """, id=import_id, props=import_record)
        rows = []
        for item in observations:
            row = dict(item)
            row["import_id"] = import_id
            rows.append(row)
        for start in range(0, len(rows), max(1, int(batch_size))):
            self.query(
                """
                UNWIND $rows AS row
                MERGE (o:HealthObservation {id:row.id})
                ON CREATE SET o.created_at=datetime()
                SET o += row, o.updated_at=datetime()
                WITH o, row
                MATCH (i:HealthImport {id:row.import_id})
                MERGE (i)-[:CONTAINS_OBSERVATION]->(o)
                WITH o
                MATCH (p:Entity {key:'himanshu'})
                MERGE (p)-[:HAS_HEALTH_OBSERVATION]->(o)
                """, rows=rows[start:start + batch_size])
        return len(rows)

    def save_knowledge(self, title, text, topic="general", source="web_research"):
        items, ts = [], _now_iso()
        for index, chunk in enumerate(chunk_text(text)):
            items.append({
                "id": _content_id("knowledge", source, title, index, chunk),
                "kind": "research", "topic": topic or "general", "source": source,
                "title": title, "content": chunk, "timestamp": ts, "authority": 35,
            })
        return self.upsert_memory_batch(items)

    def save_conversation(self, user_text, assistant_text, doc_id=None):
        content = f"User asked: {user_text}\nWinter answered: {assistant_text}"
        return self.upsert_memory_batch([{
            "id": doc_id or _content_id("turn", user_text, assistant_text),
            "kind": "conversation", "topic": "personal", "source": "conversation",
            "title": str(user_text)[:100], "content": content,
            "timestamp": _now_iso(), "authority": 80,
        }])

    def search_memories(self, query, limit=5, topic=None, kind=None):
        if not str(query or "").strip():
            return []
        candidates = {}
        try:
            rows = self.query(
                """
                MATCH (node:Memory)
                SEARCH node IN (
                  VECTOR INDEX memory_embedding FOR $embedding LIMIT $candidate_limit
                ) SCORE AS score
                WHERE ($topic IS NULL OR node.topic = $topic)
                  AND ($kind IS NULL OR node.kind = $kind)
                  AND coalesce(node.semantic_retrievable,true)=true
                  AND node.valid_to IS NULL
                  AND NOT coalesce(node.kind,'') IN ['bootstrap_evidence','bootstrap_answer','raw_interview','interview_evidence']
                  AND (NOT coalesce(node.kind,'') IN ['profile','bootstrap_profile','personal_profile']
                       OR (coalesce(node.active,true) AND NOT coalesce(node.status,'') IN ['historical','superseded','inactive']))
                RETURN node.id AS id, node.kind AS kind, node.topic AS topic,
                       node.source AS source, node.title AS title, node.content AS content,
                       node.content_hash AS content_hash,
                       node.timestamp AS timestamp, node.confidence AS confidence,
                       node.authority AS authority, score AS score,
                       node.sensitivity AS sensitivity, node.valid_to AS valid_to,
                       node.active AS active, node.status AS status, node.semantic_retrievable AS semantic_retrievable
                """,
                candidate_limit=max(limit * 8, 40), embedding=embed_text(query),
                topic=topic, kind=kind,
            )
            for rank, row in enumerate(rows, 1):
                row["rrf"] = 1.0 / (60 + rank)
                candidates[row["id"]] = row
        except Exception:
            pass
        lucene = _lucene_query(query)
        if lucene:
            try:
                rows = self.query(
                    """
                    CALL db.index.fulltext.queryNodes('memory_text', $query, {limit: $candidate_limit})
                    YIELD node, score
                    WHERE ($topic IS NULL OR node.topic = $topic)
                      AND ($kind IS NULL OR node.kind = $kind)
                      AND coalesce(node.semantic_retrievable,true)=true
                      AND node.valid_to IS NULL
                      AND NOT coalesce(node.kind,'') IN ['bootstrap_evidence','bootstrap_answer','raw_interview','interview_evidence']
                      AND (NOT coalesce(node.kind,'') IN ['profile','bootstrap_profile','personal_profile']
                           OR (coalesce(node.active,true) AND NOT coalesce(node.status,'') IN ['historical','superseded','inactive']))
                    RETURN node.id AS id, node.kind AS kind, node.topic AS topic,
                           node.source AS source, node.title AS title, node.content AS content,
                           node.content_hash AS content_hash,
                           node.timestamp AS timestamp, node.confidence AS confidence,
                           node.authority AS authority, score AS score,
                           node.sensitivity AS sensitivity, node.valid_to AS valid_to,
                           node.active AS active, node.status AS status, node.semantic_retrievable AS semantic_retrievable
                    """,
                    query=lucene, candidate_limit=max(limit * 8, 40), topic=topic, kind=kind,
                )
                for rank, row in enumerate(rows, 1):
                    if row["id"] in candidates:
                        candidates[row["id"]]["rrf"] += 1.0 / (60 + rank)
                    else:
                        row["rrf"] = 1.0 / (60 + rank)
                        candidates[row["id"]] = row
            except Exception:
                pass
        now = time.time()
        for row in candidates.values():
            freshness = 0.0
            try:
                timestamp = dt.datetime.fromisoformat(str(row.get("timestamp") or "").replace("Z", "+00:00"))
                freshness = 1.0 / (1.0 + max(0.0, (now - timestamp.timestamp()) / 86400.0) / 30.0)
            except Exception:
                pass
            row["rank"] = (
                row.get("rrf", 0) + float(row.get("authority") or 0) * 0.00004
                + float(row.get("confidence") or 0) * 0.002 + freshness * 0.001
            )
        ranked = sorted(
            candidates.values(), key=lambda row: row["rank"], reverse=True)
        # Exact repeated chunks and repeated identical conversation emissions
        # add no recall value and can monopolise the top-k. Preserve every
        # source record in the graph, but expose one copy to ordinary semantic
        # retrieval. Research/knowledge sources retain independent provenance.
        results, seen = [], set()
        for row in ranked:
            kind = str(row.get("kind") or "")
            content_hash = str(row.get("content_hash") or "")
            dedupe_key = (kind, content_hash) if (
                content_hash and kind in {"file", "conversation"}) else None
            if dedupe_key and dedupe_key in seen:
                continue
            if dedupe_key:
                seen.add(dedupe_key)
            results.append(row)
            if len(results) >= limit:
                break
        return results

