# Predicate hints are generated by a model and therefore describe concepts,
# not database enum values.  Keep storage canonical while expanding retrieval
# across relationships that answer the same user question.  This prevents a
# correct stored fact such as HAS_PORTAL_LINK from disappearing merely because
# the router called it PORTAL_URL or because an older importer used USES_PORTAL.
PREDICATE_QUERY_FAMILIES = (
    frozenset({
        "HAS_PORTAL_LINK", "USES_PORTAL", "PLACEMENTS_PORTAL_URL",
    }),
)


def canonical_predicate(predicate):
    """Normalize a predicate to the closed vocabulary."""
    text = re.sub(r"[^A-Z0-9_]", "_", str(predicate or "").upper().strip())
    text = re.sub(r"_+", "_", text).strip("_")
    return PREDICATE_ALIASES.get(text, text)


def expand_query_predicates(predicates):
    """Canonicalize and expand model-provided predicate hints."""
    expanded = []
    for value in predicates or []:
        predicate = canonical_predicate(value)
        if not predicate:
            continue
        family = next(
            (group for group in PREDICATE_QUERY_FAMILIES
             if predicate in group),
            frozenset({predicate}),
        )
        for member in sorted(family):
            if member not in expanded:
                expanded.append(member)
    return expanded


_UNRESOLVED_REFERENCE = re.compile(
    r"^(?:it|them|here|there|the above|the current one|"
    r"(?:this|that|these|those)(?:[ ]+(?:one|ones|thing|things|playlist|song|"
    r"track|video|file|folder|project|page|screen|item|place|person|app|"
    r"website))?)$",
    re.IGNORECASE,
)


def is_unresolved_reference(value):
    normalized = " ".join(str(value or "").strip().split())
    return bool(normalized and _UNRESOLVED_REFERENCE.fullmatch(normalized))


