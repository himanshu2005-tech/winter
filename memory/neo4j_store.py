_FACT_STOPWORDS = {
    "about","after","again","also","because","could","find","from","have",
    "himanshu","into","know","make","please","should","that","their","them",
    "then","there","these","they","this","want","what","when","where","which",
    "with","would","you","your",
}


def fact_query_tokens(query, limit=12):
    tokens=[]
    for token in re.findall(r"[A-Za-z0-9_]{3,}",str(query or "")):
        value=token.casefold()
        if value in _FACT_STOPWORDS or value in tokens:
            continue
        tokens.append(value)
        if len(tokens) >= limit:
            break
    return tokens


def _now_iso():
    return dt.datetime.now(dt.timezone.utc).isoformat()


def _slug(value):
    return re.sub(r"\s+", " ", str(value or "").strip()).casefold()


def _norm_key(value):
    """Punctuation-insensitive entity key used only for resolution.

    `_slug` keeps punctuation, so "IIT Bombay" and "IIT-Bombay" become two
    separate entities that never link up. This collapses everything that is
    not a letter or digit, and is stored alongside the real key rather than
    replacing it, so existing keys keep working.
    """
    return re.sub(r"[^a-z0-9]+", "", str(value or "").casefold())


def display_name(value):
    """Human-readable surface form of an entity.

    Extraction writes machine tokens like `career_success_excellent_job`, which
    are harder for a model to reason over than the words they stand for, and
    they read badly if VANTA ever says one aloud. Real names (people, places,
    phone numbers) are left exactly as they are.
    """
    text = str(value or "").strip()
    if re.match(r"https?://", text, re.I):
        return text
    if not text or " " in text:
        return text
    if re.fullmatch(r"[+\d][\d\s\-()+]*", text):  # phone numbers
        return text
    if "_" in text:
        return text.replace("_", " ").strip()
    return text


def _content_id(prefix, *values):
    raw = "\x1f".join(str(value or "") for value in values)
    return f"{prefix}_{hashlib.sha256(raw.encode('utf-8')).hexdigest()[:32]}"


def _lucene_query(text):
    tokens = re.findall(r"[A-Za-z0-9_@.\-]{2,}", text or "")[:20]
    return " OR ".join(f'"{token}"' for token in tokens)


def load_config():
    uri = os.getenv("NEO4J_URI", "bolt://127.0.0.1:7687")
    user = os.getenv("NEO4J_USER", "neo4j")
    database = os.getenv("NEO4J_DATABASE", "neo4j")
    # NEO_4J is the name used by existing VANTA installations. Keep it as a
    # compatibility fallback while preferring the conventional explicit name.
    password = os.getenv("NEO4J_PASSWORD", "") or os.getenv("NEO_4J", "")
    if not password:
        try:
            import keyring
            # The rename moved this service name, which silently orphaned the
            # credential already in Credential Manager -- the password was
            # still there, under the old name, and the graph simply refused to
            # start. Both names are read so an existing install keeps working,
            # newest first.
            for service in ("VANTA.Neo4j", "WINTER.Neo4j"):
                password = keyring.get_password(service, user) or ""
                if password:
                    break
        except Exception as exc:
            raise RuntimeError(f"Could not read Neo4j credentials: {exc}") from exc
    if not password:
        raise RuntimeError("Neo4j password is not configured in Windows Credential Manager.")
    return uri, user, password, database


class GraphStore:
    def __init__(self):
        self._driver = None
        self._lock = threading.RLock()
        self._schema_ready = False
        self._unavailable_until = 0.0
        self._last_connection_error = ""
        self._failure_count = 0
        self._last_failure_log = 0.0

    def _mark_unavailable(self, exc, cooldown=None):
        self._failure_count += 1
        if cooldown is None:
            base = min(60.0, 1.0 * (2 ** min(self._failure_count - 1, 6)))
            cooldown = base + random.uniform(0.0, base * 0.25)
        self._last_connection_error = f"{type(exc).__name__}: {exc}"
        self._unavailable_until = time.monotonic() + float(cooldown)
        driver, self._driver = self._driver, None
        self._schema_ready = False
        if driver is not None:
            try:
                driver.close()
            except Exception:
                pass
        now = time.monotonic()
        if now - self._last_failure_log >= 30.0:
            print(f"[Neo4j] Unavailable ({self._last_connection_error}); "
                  f"next health attempt in {cooldown:.1f}s.")
            self._last_failure_log = now

    def _get_driver(self):
        remaining = self._unavailable_until - time.monotonic()
        if remaining > 0:
            raise ConnectionError(
                f"Neo4j is temporarily unavailable; retry after {remaining:.1f}s"
            ) from None
        if self._driver is None:
            with self._lock:
                if self._driver is None:
                    from neo4j import GraphDatabase
                    uri, user, password, _ = load_config()
                    candidate = GraphDatabase.driver(
                        uri,
                        auth=(user, password),
                        max_connection_pool_size=20,
                        connection_timeout=2.0,
                        connection_acquisition_timeout=2.0,
                        max_transaction_retry_time=1.0,
                    )
                    try:
                        candidate.verify_connectivity()
                    except Exception as exc:
                        try:
                            candidate.close()
                        except Exception:
                            pass
                        self._mark_unavailable(exc)
                        raise ConnectionError(
                            f"Neo4j is unavailable at {uri}; VANTA will degrade and retry later"
                        ) from None
                    self._driver = candidate
                    self._unavailable_until = 0.0
                    self._last_connection_error = ""
                    if self._failure_count:
                        print("[Neo4j] Connection recovered.")
                    self._failure_count = 0
        if not self._schema_ready:
            self.ensure_schema()
        return self._driver
    def _database(self):
        return load_config()[3]

    def close(self):
        with self._lock:
            if self._driver is not None:
                self._driver.close()
                self._driver = None
                self._schema_ready = False

    def health(self):
        """Cheap authenticated health check using the shared driver/pool."""
        try:
            rows = self.query("RETURN true AS ok")
            return bool(rows and rows[0].get("ok"))
        except Exception:
            return False

    def query(self, cypher, **params):
        driver = self._get_driver()
        try:
            records, _, _ = driver.execute_query(
                cypher, parameters_=params, database_=self._database()
            )
            return [record.data() for record in records]
        except Exception as exc:
            try:
                from neo4j.exceptions import ServiceUnavailable, SessionExpired
                transient = isinstance(exc, (ServiceUnavailable, SessionExpired, ConnectionError, OSError))
            except Exception:
                transient = isinstance(exc, (ConnectionError, OSError))
            if transient:
                self._mark_unavailable(exc)
                raise ConnectionError(
                    "Neo4j connection was lost; graph access is paused briefly"
                ) from None
            raise
