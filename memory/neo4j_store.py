    def propose_inference(self, subject, predicate, object_value, rationale,
                          confidence=0.5, source_id="inference"):
        """Record a proposal without ever disturbing an existing fact.

        MERGE binds to an existing edge if the claim is already known, and
        every write here is ON CREATE, so a fact Himanshu stated can never be
        downgraded into a guess by the engine proposing the same thing.
        """
        predicate = canonical_predicate(predicate)
        subject_name = self.canonical_name(subject)
        object_name = self.canonical_name(object_value)
        subject_key, object_key = _slug(subject_name), _slug(object_name)
        if not subject_key or not object_key or not predicate:
            return None
        rows = self.query(
            """
            MERGE (s:Entity {key:$subject_key})
            ON CREATE SET s.name=$subject, s.entity_type='Entity', s.created_at=datetime()
            SET s.norm_key=coalesce(s.norm_key,$subject_norm)
            MERGE (o:Entity {key:$object_key})
            ON CREATE SET o.name=$object, o.entity_type='Entity', o.created_at=datetime()
            SET o.norm_key=coalesce(o.norm_key,$object_norm)
            MERGE (s)-[r:FACT {predicate:$predicate, object_key:$object_key}]->(o)
            ON CREATE SET r.id=$fact_id, r.fact_id=$fact_id,
                r.fact_class='derived_inference', r.review_status='pending_confirmation',
                r.evidence_type='inferred', r.rationale=$rationale,
                r.confidence=$confidence, r.authority=20, r.sensitivity='private',
                r.source_id=$source_id, r.mention_count=1,
                r.valid_from=toString(datetime()), r.created_at=datetime(),
                r.claim_key=$claim_key, r.autonomy_eligible=false,
                r.confirmation_required=true
            ON MATCH SET r.mention_count = CASE
                    WHEN coalesce(r.fact_class,'')='derived_inference'
                    THEN coalesce(r.mention_count,1) + 1
                    ELSE coalesce(r.mention_count,1) END,
                r.last_proposed_at = CASE
                    WHEN coalesce(r.fact_class,'')='derived_inference'
                    THEN datetime() ELSE r.last_proposed_at END
            RETURN coalesce(r.fact_class,'') AS fact_class,
                   coalesce(r.review_status,'') AS review_status
            """,
            subject_key=subject_key, subject=subject_name,
            object_key=object_key, object=object_name,
            subject_norm=_norm_key(subject_name), object_norm=_norm_key(object_name),
            predicate=predicate, rationale=str(rationale or "")[:600],
            confidence=float(max(0.0, min(1.0, confidence))),
            source_id=str(source_id),
            fact_id=_content_id("inference", subject_key, predicate, object_key),
            claim_key=f"{subject_key}:{predicate}",
        )
        if not rows:
            return None
        # Already a real fact — the proposal added nothing and changed nothing.
        if rows[0]["fact_class"] != "derived_inference":
            return None
        return f"{subject_name} -{predicate}-> {object_name}"

