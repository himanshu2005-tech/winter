def chunk_text(text, chunk_size=1000, overlap=200):
    value = str(text or "")
    if not value.strip():
        return []
    chunks, start = [], 0
    while start < len(value):
        chunks.append(value[start:start + chunk_size])
        start += max(1, chunk_size - overlap)
    return chunks


