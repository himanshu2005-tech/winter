    def set_inference_status(self, subject, predicate, object_value=None, accept=True):
        """Confirm a proposal into a retrievable fact, or tombstone it.

        A rejected proposal keeps its row so the engine will not raise the same
        idea again next time it runs.
        """
        predicate = canonical_predicate(predicate)
        return self.query(
            """
            MATCH (s:Entity)-[r:FACT]->(o:Entity)
            WHERE s.key=$subject_key AND r.predicate=$predicate
              AND coalesce(r.fact_class,'')='derived_inference'
              AND ($object_key IS NULL OR r.object_key=$object_key)
            SET r.review_status = CASE WHEN $accept THEN 'accepted' ELSE 'rejected' END,
                r.valid_to = CASE WHEN $accept THEN NULL ELSE toString(datetime()) END,
                r.confidence = CASE WHEN $accept THEN 0.9 ELSE coalesce(r.confidence,0.5) END,
                r.authority = CASE WHEN $accept THEN 70 ELSE 20 END,
                r.updated_at = datetime()
            RETURN s.name AS subject, r.predicate AS predicate, o.name AS object
            """,
            subject_key=_slug(self.canonical_name(subject)),
            predicate=predicate,
            object_key=_slug(self.canonical_name(object_value)) if object_value else None,
            accept=bool(accept),
        )

    def neighborhood(self, entities, hops=1):
        frontier = {_slug(value) for value in entities if str(value or "").strip()}
        visited, edges = set(), set()
        for _ in range(max(1, min(int(hops), 3))):
            if not frontier:
                break
            rows = self.query(
                """
                MATCH (s:Entity)-[r:FACT]->(o:Entity)
                WHERE r.valid_to IS NULL AND (s.key IN $keys OR o.key IN $keys)
                RETURN s.key AS skey,s.name AS subject,r.predicate AS predicate,
                       o.key AS okey,o.name AS object
                """,
                keys=list(frontier),
            )
            next_frontier = set()
            for row in rows:
                edges.add((row["subject"], row["predicate"], row["object"]))
                next_frontier.update((row["skey"], row["okey"]))
            visited.update(frontier)
            frontier = next_frontier - visited
        return list(edges)

