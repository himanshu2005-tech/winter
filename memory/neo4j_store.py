    def canonical_name(self, name):
        value = str(name or "").strip()
        if not value:
            return value
        rows = self.query(
            "MATCH (e:Entity) WHERE e.key=$key OR any(a IN coalesce(e.aliases,[]) WHERE toLower(a)=$key) "
            "RETURN e.name AS name LIMIT 1",
            key=_slug(value),
        )
        if rows:
            return rows[0]["name"]
        # Fall back to punctuation-insensitive matching so a fact about
        # "IIT-Bombay" attaches to the existing "IIT Bombay" entity.
        norm = _norm_key(value)
        if norm:
            rows = self.query(
                "MATCH (e:Entity) WHERE e.norm_key=$norm RETURN e.name AS name LIMIT 1",
                norm=norm,
            )
            if rows:
                return rows[0]["name"]
        return value

    def add_fact(self, subject, predicate, object_value, confidence=1.0, source_id="user_stated", valid_from=None, valid_to=None, **metadata):
        predicate = canonical_predicate(predicate)
        from memory.fact_validation import validate_fact
        validate_fact(subject, predicate, object_value, confidence, metadata)
        if is_unresolved_reference(subject) or is_unresolved_reference(object_value):
            return (
                "[Rejected] Durable facts require a grounded entity name; "
                f"unresolved reference: {object_value!r}")
        subject_name, object_name = self.canonical_name(subject), self.canonical_name(object_value)
        subject_key, object_key = _slug(subject_name), _slug(object_name)
        # A fact id identifies one validity episode.  Including the episode
        # start keeps a re-asserted, previously retired fact distinct from its
        # historical edge.  Retrying while the edge is current remains
        # idempotent because the current edge is matched below and keeps its id.
        episode_start = str(valid_from or _now_iso())
        fact_id = _content_id(
            "fact", subject_key, predicate, object_key, source_id, episode_start)
        functional = (predicate in FUNCTIONAL_PREDICATES
                      or metadata.get("single_valued") is True)
        claim_key = metadata.get("claim_key") or (
            f"{subject_key}:{predicate}" if functional
            else f"{subject_key}:{predicate}:{object_key}")
        evidence_quote = (
            " ".join(str(metadata.get("evidence_quote") or "").split())[:400]
            or None)
        evidence_id = _content_id(
            "fact_evidence", subject_key, predicate, object_key,
            str(source_id), evidence_quote or "")
        self.query(
            """
            MERGE (s:Entity {key:$subject_key})
            ON CREATE SET s.name=$subject, s.entity_type='Entity', s.created_at=datetime()
            SET s.norm_key=coalesce(s.norm_key,$subject_norm)
            MERGE (o:Entity {key:$object_key})
            ON CREATE SET o.name=$object, o.entity_type='Entity', o.created_at=datetime()
            SET o.norm_key=coalesce(o.norm_key,$object_norm)
            WITH s,o OPTIONAL MATCH (s)-[old:FACT]->()
            WHERE $functional AND old.predicate=$predicate AND old.valid_to IS NULL
              AND coalesce(old.object_key,endNode(old).key)<>$object_key
              AND coalesce(old.confidence,0.0)<=$confidence
              AND coalesce(old.authority,50)<=$authority
            SET old.valid_to=toString(datetime()),
                old.superseded_by_fact_id=$fact_id,
                old.correction_reason=coalesce($correction_reason,
                                               'new explicit value')
            // Only a CURRENTLY VALID edge may be updated in place. Matching on
            // predicate+object_key alone would also bind edges that were
            // retired on purpose, and writing valid_to=NULL onto them brings
            // dead facts back to life — a re-run of the contact sync would
            // resurrect every stale contact it had ever superseded.
            WITH DISTINCT s,o
            OPTIONAL MATCH (s)-[cur:FACT]->(o)
            WHERE cur.predicate=$predicate AND cur.object_key=$object_key
              AND cur.valid_to IS NULL
            WITH s,o,cur LIMIT 1
            FOREACH (_ IN CASE WHEN cur IS NULL THEN [1] ELSE [] END |
              CREATE (s)-[n:FACT {predicate:$predicate, object_key:$object_key}]->(o)
              SET n.created_at=datetime(), n.mention_count=1,
                  n.id=$fact_id, n.last_seen=toString(datetime()),
                  n.confidence=$confidence, n.source_id=$source_id,
                  n.valid_from=coalesce($valid_from,toString(datetime())),
                  n.valid_to=$valid_to, n.updated_at=datetime(),
                  n.fact_id=$fact_id, n.fact_class=$fact_class,
                  n.evidence_type=$evidence_type, n.authority=$authority,
                  n.sensitivity=$sensitivity, n.autonomy_eligible=$autonomy_eligible,
                  n.autonomy_scope=$autonomy_scope,
                  n.confirmation_required=$confirmation_required,
                  n.review_status=$review_status, n.claim_key=$claim_key,
                  n.supersedes_fact_id=$supersedes_fact_id,
                  n.superseded_by_fact_id=$superseded_by_fact_id,
                  n.correction_reason=$correction_reason,
                  n.evidence_quote=$evidence_quote, n.evidence_ref=$evidence_ref)
            FOREACH (_ IN CASE WHEN cur IS NULL THEN [] ELSE [1] END |
              SET cur.mention_count=coalesce(cur.mention_count,1)+1,
                  cur.last_seen=toString(datetime()),
                  cur.confidence=CASE WHEN coalesce(cur.confidence,0.0) < $confidence
                                      THEN $confidence ELSE cur.confidence END,
                  cur.fact_class=CASE WHEN $authority>coalesce(cur.authority,0)
                                      THEN $fact_class ELSE cur.fact_class END,
                  cur.evidence_type=CASE WHEN $authority>coalesce(cur.authority,0)
                                      THEN $evidence_type ELSE cur.evidence_type END,
                  cur.review_status=CASE WHEN $authority>coalesce(cur.authority,0)
                                      THEN $review_status ELSE cur.review_status END,
                  cur.authority=CASE WHEN coalesce(cur.authority,0) < $authority
                                     THEN $authority ELSE cur.authority END,
                  cur.sensitivity=CASE
                    WHEN NOT (coalesce(cur.sensitivity,'private') IN ['public','private','sensitive','restricted']) THEN 'restricted'
                    WHEN coalesce(cur.sensitivity,'private')='restricted' OR $sensitivity='restricted' THEN 'restricted'
                    WHEN coalesce(cur.sensitivity,'private')='sensitive' OR $sensitivity='sensitive' THEN 'sensitive'
                    WHEN coalesce(cur.sensitivity,'private')='private' OR $sensitivity='private' THEN 'private'
                    ELSE 'public' END,
                  cur.updated_at=datetime(),
                  cur.claim_key=coalesce(cur.claim_key,$claim_key))
            WITH s,o
            MATCH (s)-[current:FACT]->(o)
            WHERE current.predicate=$predicate AND current.object_key=$object_key
              AND current.valid_to IS NULL
            MERGE (e:FactEvidence {id:$evidence_id})
            ON CREATE SET e.created_at=datetime(),e.source_id=$source_id,
                          e.quote=$evidence_quote,e.evidence_ref=$evidence_ref,
                          e.evidence_type=$evidence_type,e.sensitivity=$sensitivity
            SET e.fact_id=coalesce(current.fact_id,current.id),e.last_seen=datetime()
            MERGE (e)-[:SUPPORTS_SUBJECT]->(s)
            MERGE (e)-[:SUPPORTS_OBJECT]->(o)
            """,
            subject_key=subject_key, subject=subject_name, object_key=object_key,
            object=object_name, predicate=predicate, confidence=float(confidence),
            subject_norm=_norm_key(subject_name), object_norm=_norm_key(object_name),
            source_id=str(source_id), fact_id=fact_id,
            functional=functional,
            valid_from=episode_start, valid_to=valid_to,
            fact_class=metadata.get("fact_class","explicit_user_fact"),
            evidence_type=metadata.get("evidence_type","user_stated"),
            authority=int(metadata.get("authority",80)),
            sensitivity=metadata.get("sensitivity","private"),
            autonomy_eligible=bool(metadata.get("autonomy_eligible",False)),
            autonomy_scope=metadata.get("autonomy_scope","advisory"),
            confirmation_required=bool(metadata.get("confirmation_required",False)),
            review_status=metadata.get("review_status","accepted"),
            claim_key=claim_key,
            supersedes_fact_id=metadata.get("supersedes_fact_id"),
            superseded_by_fact_id=metadata.get("superseded_by_fact_id"),
            correction_reason=metadata.get("correction_reason"),
            # The sentence this was actually drawn from, so the claim can be
            # checked later instead of taken on trust.
            evidence_quote=evidence_quote,
            evidence_ref=metadata.get("evidence_ref") or None,
            evidence_id=evidence_id,
        )
        return f"Added fact: {subject_name} -{predicate}-> {object_name}"

