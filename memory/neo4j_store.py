    def auto_promote_inferences(self, min_confidence=0.90, min_sightings=2,
                                limit=10):
        """Promote corroborated proposals without asking, and say which.

        Self-reported confidence is not evidence. The number arrives in the
        same JSON that makes the claim, and the engine cheerfully attaches
        0.99 to a restatement of two data points it has already been given --
        "tracks daily health metrics", from a step count appearing twice. A
        threshold on that number alone would promote almost everything,
        including the vacuous.

        Repetition across independent passes is evidence of a different kind:
        the engine read the facts again, on a later run, and arrived at the
        same place. That is what `min_sightings` counts.

        What promotion does NOT change, deliberately:

          fact_class stays 'derived_inference', so the engine still never
          reads its own output -- the rule that stops confidence compounding
          on nothing;
          autonomy_eligible stays false and confirmation_required stays true,
          so a promoted belief can never authorize an action;
          authority is 50, below the 70 a human confirmation gives and well
          below a stated fact, so anything Himanshu says wins a conflict;
          review_status becomes 'auto_accepted' rather than 'accepted', so
          what was promoted on VANTA's own judgement stays listable and
          revocable separately from what he agreed to.
        """
        return self.query(
            """
            MATCH (s:Entity)-[r:FACT]->(o:Entity)
            WHERE coalesce(r.fact_class,'')='derived_inference'
              AND coalesce(r.review_status,'')='pending_confirmation'
              AND r.valid_to IS NULL
              AND coalesce(r.confidence,0.0) >= $min_confidence
              AND coalesce(r.mention_count,1) >= $min_sightings
            SET r.review_status='auto_accepted',
                r.authority=50,
                r.auto_accepted_at=datetime(),
                r.updated_at=datetime()
            RETURN s.name AS subject, r.predicate AS predicate,
                   o.name AS object, coalesce(r.confidence,0.0) AS confidence,
                   coalesce(r.mention_count,1) AS sightings
            ORDER BY coalesce(r.confidence,0.0) DESC
            LIMIT $limit
            """,
            min_confidence=float(min_confidence),
            min_sightings=int(min_sightings),
            limit=int(limit),
        )

