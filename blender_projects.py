def _atomic_json(path, payload):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_suffix(path.suffix + ".tmp")
    temp.write_text(json.dumps(payload, ensure_ascii=False, indent=2),
                    encoding="utf-8")
    os.replace(temp, path)


def _read_json(path, default=None):
    try:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError, TypeError):
        return default


def _paths(base_dir, project):
    root = Path(projects.project_path(base_dir, project))
    runtime = root / RUNTIME_DIR
    return {
        "root": root, "runtime": runtime,
        "commands": runtime / "commands", "results": runtime / "results",
        "revisions": runtime / "revisions",
        "ready": runtime / "ready.json", "bridge": runtime / "bridge.py",
        "active": runtime / "active.json", "log": runtime / "blender.log",
        "manifest": runtime / MANIFEST_NAME,
        "artifact": root / ARTIFACT_NAME,
    }


def _ensure_project(base_dir, project):
    name = " ".join(str(project or "").split())
    if not name:
        raise BlenderProjectError("RUNTIME_APPLY needs a project name.")
    root = Path(projects.project_path(base_dir, name))
    if not root.exists():
        result = projects.create(
            base_dir, name, "Persistent Blender project managed by VANTA",
            "Python / Blender")
        if result.startswith("[Error]"):
            raise BlenderProjectError(result)
    projects.set_active(base_dir, name)
    paths = _paths(base_dir, name)
    for key in ("runtime", "commands", "results", "revisions"):
        paths[key].mkdir(parents=True, exist_ok=True)
    if not paths["bridge"].exists():
        session = uuid.uuid4().hex
        paths["bridge"].write_text(
            _BRIDGE_SOURCE.replace("__SESSION__", session), encoding="utf-8")
    return name, paths


def _process_alive(pid):
    try:
        import ctypes
        SYNCHRONIZE = 0x00100000
        handle = ctypes.windll.kernel32.OpenProcess(SYNCHRONIZE, False, int(pid))
        if not handle:
            return False
        try:
            return ctypes.windll.kernel32.WaitForSingleObject(handle, 0) == 258
        finally:
            ctypes.windll.kernel32.CloseHandle(handle)
    except Exception:
        return False


def _crash_evidence(paths, since=0.0):
    """Return bounded Blender crash evidence, never a guessed diagnosis."""
    candidates = []
    roots = (paths["root"], paths["runtime"], Path(tempfile.gettempdir()))
    for root in roots:
        try:
            for pattern in ("blender*.crash.txt", "blender.crash.txt"):
                for path in Path(root).glob(pattern):
                    if path.is_file() and path.stat().st_mtime >= since - 5:
                        candidates.append(path)
        except OSError:
            continue
    active = _read_json(paths.get("active", ""), {}) or {}
    active_text = ""
    if active:
        active_text = (f" Active operation={active.get('operation')} "
                       f"request={active.get('id')} code={active.get('code_path')}.")
    log_text = ""
    try:
        log_tail = paths["log"].read_text(
            encoding="utf-8", errors="replace")[-2000:].strip()
        if log_tail:
            log_text = f" Blender log tail: {log_tail}"
    except OSError:
        pass
    if not candidates:
        return active_text + log_text
    newest = max(candidates, key=lambda path: path.stat().st_mtime)
    try:
        tail = newest.read_text(encoding="utf-8", errors="replace")[-2000:]
    except OSError:
        tail = ""
    return (active_text + f" Crash report: {newest}."
            + (f" Tail: {tail}" if tail else "") + log_text)


def _ensure_bridge(paths, timeout=30):
    ready = _read_json(paths["ready"], {}) or {}
    if ready.get("pid") and _process_alive(ready["pid"]):
        return ready, False
    try:
        paths["ready"].unlink()
    except OSError:
        pass
    blender, error = codetools.find_blender()
    if error:
        raise BlenderProjectError(error)
    command = [blender]
    if paths["artifact"].exists():
        command.append(str(paths["artifact"]))
    command.extend(["--python", str(paths["bridge"])])
    # Persist Blender's own output. Discarding it made a renderer/GPU failure,
    # Python exception during startup and a user-close all look identical.
    log_handle = open(paths["log"], "a", encoding="utf-8", errors="replace")
    try:
        log_handle.write(f"\n--- launch {time.strftime('%Y-%m-%d %H:%M:%S')} ---\n")
        log_handle.flush()
        process = subprocess.Popen(
            command, cwd=str(paths["root"]), stdin=subprocess.DEVNULL,
            stdout=log_handle, stderr=subprocess.STDOUT)
    finally:
        log_handle.close()
    deadline = time.monotonic() + max(3, min(float(timeout), 90))
    while time.monotonic() < deadline:
        ready = _read_json(paths["ready"], {}) or {}
        if ready.get("pid") == process.pid:
            return ready, True
        if process.poll() is not None:
            raise BlenderProjectError(
                f"Blender exited with code {process.returncode} before its "
                "project bridge became ready.")
        time.sleep(0.15)
    raise BlenderProjectError("Blender opened but its project bridge did not become ready in time.")


def _validate_code(code):
    text = str(code or "")
    if not text.strip():
        raise BlenderProjectError("RUNTIME_APPLY needs Python code in its body.")
    if len(text.encode("utf-8")) > MAX_CODE_BYTES:
        raise BlenderProjectError("The Blender revision is larger than 500 KB.")
    try:
        tree = ast.parse(text)
    except SyntaxError as exc:
        raise BlenderProjectError(
            f"Blender Python does not parse at line {exc.lineno}: {exc.msg}") from exc
    blocked_modules = {
        "os", "subprocess", "socket", "requests", "urllib", "http", "ftplib",
        "smtplib", "shutil", "pathlib", "ctypes", "winreg", "sys",
    }
    blocked_calls = {"open", "exec", "eval", "compile", "__import__", "input"}
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            names = {alias.name.split(".", 1)[0] for alias in node.names}
            if names & blocked_modules:
                raise BlenderProjectError(
                    "Blender project code may modify the scene, not the OS or network.")
        if isinstance(node, ast.ImportFrom):
            if (node.module or "").split(".", 1)[0] in blocked_modules:
                raise BlenderProjectError(
                    "Blender project code may modify the scene, not the OS or network.")
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name):
            if node.func.id in blocked_calls:
                raise BlenderProjectError(
                    f"{node.func.id}() is not allowed in Blender project code.")

    # Persistent scenes must remain addressable by meaning, not by whatever
    # display names Blender happens to allocate (Cube.017, Sphere.122, ...).
    # Without this, a visually plausible first pass cannot be edited reliably
    # on the next voice request.  Enforce the adapter's generic identity
    # contract before Blender is allowed to mutate or save the artifact.
    creates_geometry = bool(re.search(
        r"bpy\.ops\.mesh\.primitive_[A-Za-z0-9_]+_add\s*\(|"
        r"bpy\.data\.objects\.new\s*\(", text))
    if creates_geometry and "vanta_id" not in text:
        raise BlenderProjectError(
            "New Blender geometry needs a durable obj['vanta_id'] property "
            "so later requests can find and edit it safely.")

    creates_links = bool(
        re.search(r"primitive_(?:cylinder|curve)_add\s*\(", text)
        and re.search(r"\b(?:edge|link|connect|network)\b", text,
                      re.IGNORECASE))
    if creates_links and not ({"vanta_source", "vanta_target"} <= set(
            re.findall(r"vanta_(?:source|target)", text))):
        raise BlenderProjectError(
            "Connection geometry needs both vanta_source and vanta_target "
            "properties so the runtime can verify and update its endpoints.")
    return text


def _submit(paths, operation, code_path="", timeout=120, interrupt_event=None,
            bridge_pid=None):
    request_id = uuid.uuid4().hex
    command = {"id": request_id, "operation": operation,
               "code_path": str(code_path or "")}
    command_path = paths["commands"] / f"{request_id}.json"
    result_path = paths["results"] / f"{request_id}.json"
    _atomic_json(command_path, command)
    started_wall = time.time()
    deadline = time.monotonic() + max(3, min(float(timeout), 600))
    while time.monotonic() < deadline:
        result = _read_json(result_path)
        if result is not None:
            try:
                result_path.unlink()
            except OSError:
                pass
            return result
        if interrupt_event is not None and interrupt_event.is_set():
            (paths["commands"] / f"{request_id}.cancel").touch()
            return {"ok": False, "cancelled": True,
                    "error": "Abort requested; Blender was told to skip the revision if it had not started."}
        pid = bridge_pid or (_read_json(paths["ready"], {}) or {}).get("pid")
        if pid and not _process_alive(pid):
            return {"ok": False, "crashed": True, "pid": pid,
                    "error": (f"Blender process {pid} exited before returning a receipt."
                              + _crash_evidence(paths, started_wall))}
        time.sleep(0.1)
    return {"ok": False, "timeout": True,
            "error": ("Blender is still alive but did not return a receipt before the timeout; "
                      "the revision may still be working. Check RUNTIME_STATUS before retrying.")}


def _manifest(paths):
    return _read_json(paths["manifest"], {}) or {
        "schema_version": 1, "adapter": "blender", "revision": 0,
        "history": [],
    }


def _summary_text(summary, limit=24):
    summary = summary or {}
    objects = summary.get("objects") or []
    semantic = []
    for row in objects:
        props = row.get("properties") or {}
        identity = props.get("vanta_id")
        if identity:
            semantic.append(
                f"{identity}={row.get('name')}<{row.get('type')}>@{row.get('location')}")
    edge_count = len(summary.get("edges") or [])
    detail = "; ".join(semantic[:limit]) or "no semantic IDs yet"
    if len(semantic) > limit:
        detail += f"; ... {len(semantic) - limit} more"
    text = (f"objects={summary.get('object_count', len(objects))}, "
            f"collections={summary.get('collection_count', 0)}, "
            f"semantic_objects={len(semantic)}, edges={edge_count}. {detail}")
    warnings = _quality_warnings(summary)
    if warnings:
        text += " Presentation warnings: " + "; ".join(warnings)
    return text


def _quality_warnings(summary):
    """Detect generic scene clutter that makes later edits/presentation unsafe."""
    objects = list((summary or {}).get("objects") or [])
    identifiers = {}
    for row in objects:
        identity = str((row.get("properties") or {}).get("vanta_id") or "").strip()
        if identity:
            identifiers.setdefault(identity, []).append(str(row.get("name") or ""))
    duplicates = sorted(key for key, names in identifiers.items() if len(names) > 1)
    warnings = []
    if duplicates:
        sample = ", ".join(duplicates[:4])
        warnings.append(
            f"duplicate semantic IDs ({sample}); retries must update existing objects, not add copies")
    camera_count = sum(1 for row in objects if row.get("type") == "CAMERA")
    if camera_count > 1:
        warnings.append(f"{camera_count} cameras exist; reuse one deliberate presentation camera")
    label_count = sum(1 for row in objects if row.get("type") == "FONT")
    if len(objects) >= 20 and label_count > max(8, len(objects) // 3):
        warnings.append(
            f"{label_count} text objects create visual clutter; consolidate repeated labels into a legend")
    collection_count = int((summary or {}).get("collection_count") or 0)
    if len(objects) >= 20 and collection_count <= 1:
        warnings.append("the scene is ungrouped; organise major sections into collections")
    return warnings


def apply(base_dir, project, code, instruction="", timeout=120,
          open_after=True, interrupt_event=None):
    name, paths = _ensure_project(base_dir, project)
    code = _validate_code(code)
    manifest = _manifest(paths)
    revision = int(manifest.get("revision", 0)) + 1
    pending = paths["revisions"] / f"{revision:04d}.pending.py"
    final = paths["revisions"] / f"{revision:04d}.py"
    pending.write_text(code if code.endswith("\n") else code + "\n",
                       encoding="utf-8")
    ready, opened = _ensure_bridge(paths, timeout=min(timeout, 45))
    result = _submit(paths, "apply", pending, timeout=timeout,
                     interrupt_event=interrupt_event,
                     bridge_pid=ready.get("pid"))
    if not result.get("ok"):
        failed = pending.with_name(f"{revision:04d}.failed.py")
        try:
            os.replace(pending, failed)
        except OSError:
            pass
        label = "[Cancelled]" if result.get("cancelled") else "[Error]"
        failure = (f"{label} Blender revision {revision} was not committed: "
                   f"{result.get('error', 'unknown error')}")
        if result.get("crashed"):
            failure += (" The failed revision was preserved for diagnosis and will not be "
                        "run again automatically. Reopen with RUNTIME_RESUME after correcting it.")
        return failure
    if not paths["artifact"].exists() or paths["artifact"].stat().st_size < 512:
        return (f"[Error] Blender reported revision {revision} complete, but "
                f"{paths['artifact']} was not written correctly.")
    os.replace(pending, final)
    shutil.copy2(final, paths["runtime"] / "latest.py")
    history = list(manifest.get("history") or [])[-99:]
    history.append({"revision": revision, "instruction": str(instruction or ""),
                    "script": str(final.relative_to(paths["root"])),
                    "applied_at": time.time(),
                    "summary": result.get("summary") or {}})
    manifest.update({
        "schema_version": 1, "adapter": "blender", "project": name,
        "revision": revision, "artifact": ARTIFACT_NAME,
        "bridge_pid": ready.get("pid"), "history": history,
        "updated_at": time.time(),
    })
    _atomic_json(paths["manifest"], manifest)
    try:
        import artifact_context
        artifact_context.record(str(paths["artifact"]), "blender_project",
                                "RUNTIME_APPLY",
                                {"project": name, "revision": revision})
    except Exception:
        pass
    opened_text = " Blender opened visibly." if opened else " Live Blender session updated."
    return (f"[Success] Blender project '{name}' revision={revision}; "
            f"artifact={paths['artifact']}; bridge_pid={ready.get('pid')}."
            f"{opened_text} Verified scene: {_summary_text(result.get('summary'))}")


def status(base_dir, project, timeout=30):
    name, paths = _ensure_project(base_dir, project)
    manifest = _manifest(paths)
    if not paths["artifact"].exists() and not manifest.get("revision"):
        return f"[Success] Blender project '{name}' exists with revision=0 and no scene yet."
    ready, opened = _ensure_bridge(paths, timeout=timeout)
    result = _submit(paths, "inspect", timeout=timeout,
                     bridge_pid=ready.get("pid"))
    if not result.get("ok"):
        return f"[Error] Could not inspect Blender project '{name}': {result.get('error')}"
    return (f"[Success] Blender project '{name}' revision={manifest.get('revision', 0)}; "
            f"artifact={paths['artifact']}; bridge_pid={ready.get('pid')}; "
            f"{'reopened; ' if opened else ''}{_summary_text(result.get('summary'))}")


def open_project(base_dir, project, timeout=30):
    name, paths = _ensure_project(base_dir, project)
    ready, opened = _ensure_bridge(paths, timeout=timeout)
    return (f"[Success] Blender project '{name}' is "
            f"{'open' if opened else 'already open'}; "
            f"bridge_pid={ready.get('pid')}; artifact={paths['artifact']}.")


def present(base_dir, project, enabled=True, timeout=30):
    """Enter or leave a model-only Blender viewport without changing geometry."""
    name, paths = _ensure_project(base_dir, project)
    ready, opened = _ensure_bridge(paths, timeout=timeout)
    command_path = paths["runtime"] / "presentation.py"
    command_path.write_text(_presentation_code(bool(enabled)), encoding="utf-8")
    try:
        result = _submit(paths, "apply", command_path, timeout=timeout,
                         bridge_pid=ready.get("pid"))
    finally:
        try:
            command_path.unlink()
        except OSError:
            pass
    if not result.get("ok"):
        return (f"[Error] Could not {'enter' if enabled else 'leave'} Blender "
                f"presentation mode for '{name}': {result.get('error', 'unknown error')}")
    state = "active" if enabled else "closed"
    navigation = (" Orbit, pan, and zoom remain enabled."
                  if enabled else " The normal Blender workspace is restored.")
    return (f"[Success] Blender presentation mode is {state} for '{name}'; "
            f"bridge_pid={ready.get('pid')}.{navigation} "
            f"Scene: {_summary_text(result.get('summary'))}")


def context_block(base_dir, project):
    """Compact durable state for resolving conversational follow-up edits."""
    paths = _paths(base_dir, project)
    manifest = _read_json(paths["manifest"], {}) or {}
    if not manifest:
        return ""
    history = manifest.get("history") or []
    latest = history[-1] if history else {}
    instruction = str(latest.get("instruction") or "").strip()
    summary = latest.get("summary") or {}
    lines = [
        "EXECUTABLE PROJECT RUNTIME:",
        f"  adapter=blender project={project!r} revision={manifest.get('revision', 0)}",
        f"  artifact={paths['artifact']}",
    ]
    if instruction:
        lines.append(f"  last_change={instruction[:500]}")
    lines.append(f"  scene={_summary_text(summary, limit=40)}")
    lines.append(
        "  Follow-up edits must query existing objects by their vanta_id and "
        "semantic properties; preserve those identities and modify the scene incrementally.")
    return "\n".join(lines)
