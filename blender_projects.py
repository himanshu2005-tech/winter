# -*- coding: utf-8 -*-
"""A persistent, visible Blender project runtime for VANTA.

Each project owns a .blend artifact, immutable Python revisions, a manifest,
and a tiny file-queue bridge running inside the visible Blender process.
Follow-up edits execute against the already-loaded scene instead of rebuilding
from a screenshot or starting from an empty file.
"""

import ast
import json
import os
import re
import shutil
import subprocess
import tempfile
import time
import uuid
from pathlib import Path

import codetools
import projects


RUNTIME_DIR = ".vanta_blender"
ARTIFACT_NAME = "scene.blend"
MANIFEST_NAME = "manifest.json"
MAX_CODE_BYTES = 500_000


class BlenderProjectError(Exception):
    pass


_BRIDGE_SOURCE = r'''# Generated by VANTA. Runs inside Blender.
import bpy, json, os, traceback, time, builtins

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUNTIME = os.path.dirname(os.path.abspath(__file__))
COMMANDS = os.path.join(RUNTIME, "commands")
RESULTS = os.path.join(RUNTIME, "results")
ARTIFACT = os.path.join(ROOT, "scene.blend")
ACTIVE = os.path.join(RUNTIME, "active.json")
SESSION = "__SESSION__"

def _atomic_json(path, payload):
    temp = path + ".tmp"
    with open(temp, "w", encoding="utf-8") as handle:
        json.dump(payload, handle, ensure_ascii=False, indent=2)
    os.replace(temp, path)

def _value(value):
    if isinstance(value, (str, int, float, bool)) or value is None:
        return value
    try:
        return list(value)
    except Exception:
        return str(value)

def _summary():
    rows = []
    edges = []
    for obj in list(bpy.data.objects)[:1000]:
        props = {}
        for key in obj.keys():
            if key.startswith("vanta_") or key in {
                    "layer_index", "node_index", "source_id", "target_id"}:
                props[key] = _value(obj[key])
        row = {
            "name": obj.name, "type": obj.type,
            "location": [round(float(v), 4) for v in obj.location],
            "parent": obj.parent.name if obj.parent else None,
            "properties": props,
        }
        rows.append(row)
        source = props.get("vanta_source") or props.get("source_id")
        target = props.get("vanta_target") or props.get("target_id")
        if source and target:
            edges.append({"object": obj.name, "source": source,
                          "target": target})
    return {
        "scene": bpy.context.scene.name,
        "object_count": len(bpy.data.objects),
        "collection_count": len(bpy.data.collections),
        "objects": rows,
        "edges": edges,
    }

def _execute(payload):
    request_id = payload["id"]
    result = {"id": request_id, "ok": False, "session": SESSION}
    try:
        operation = payload.get("operation", "inspect")
        _atomic_json(ACTIVE, {"id": request_id, "operation": operation,
                              "started_at": time.time(),
                              "code_path": payload.get("code_path", "")})
        cancelled = os.path.join(COMMANDS, request_id + ".cancel")
        if os.path.exists(cancelled):
            result["cancelled"] = True
            result["error"] = "cancelled before execution"
            return result
        if operation == "apply":
            code_path = os.path.abspath(payload["code_path"])
            if os.path.commonpath([code_path, RUNTIME]) != RUNTIME:
                raise RuntimeError("code path escaped the project runtime")
            with open(code_path, encoding="utf-8") as handle:
                code = handle.read()
            allowed_modules = {"bpy", "math", "mathutils", "random",
                               "colorsys", "itertools"}
            def _safe_import(name, globals=None, locals=None, fromlist=(), level=0):
                if name.split(".", 1)[0] not in allowed_modules:
                    raise ImportError("module is outside the Blender project sandbox")
                return builtins.__import__(name, globals, locals, fromlist, level)
            safe_builtins = {
                name: getattr(builtins, name) for name in (
                    "abs", "all", "any", "bool", "dict", "enumerate",
                    "Exception", "float", "getattr", "hasattr", "int",
                    "isinstance", "len", "list", "map", "max", "min",
                    "next", "object", "print", "range", "reversed", "round",
                    "set", "setattr", "slice", "sorted", "str", "sum",
                    "tuple", "type", "ValueError", "zip")}
            safe_builtins["__import__"] = _safe_import
            namespace = {
                "bpy": bpy,
                "PROJECT_ROOT": ROOT,
                "ARTIFACT_PATH": ARTIFACT,
                "__name__": "__vanta_blender_revision__",
                "__builtins__": safe_builtins,
            }
            exec(compile(code, code_path, "exec"), namespace, namespace)
            bpy.context.view_layer.update()
            bpy.ops.wm.save_as_mainfile(filepath=ARTIFACT, check_existing=False)
        result["summary"] = _summary()
        result["artifact"] = ARTIFACT
        result["ok"] = True
        return result
    except Exception as exc:
        result["error"] = str(exc)
        result["traceback"] = traceback.format_exc()[-8000:]
        return result
    finally:
        try: os.remove(ACTIVE)
        except OSError: pass

def _poll():
    try:
        for name in sorted(os.listdir(COMMANDS)):
            if not name.endswith(".json"):
                continue
            path = os.path.join(COMMANDS, name)
            claimed = path + ".running"
            try:
                os.replace(path, claimed)
                with open(claimed, encoding="utf-8") as handle:
                    payload = json.load(handle)
                result = _execute(payload)
                _atomic_json(os.path.join(RESULTS, payload["id"] + ".json"),
                             result)
            except Exception as exc:
                request_id = name[:-5]
                _atomic_json(os.path.join(RESULTS, request_id + ".json"), {
                    "id": request_id, "ok": False,
                    "error": str(exc), "traceback": traceback.format_exc()[-8000:]})
            finally:
                try: os.remove(claimed)
                except OSError: pass
    finally:
        return 0.25

os.makedirs(COMMANDS, exist_ok=True)
os.makedirs(RESULTS, exist_ok=True)
_atomic_json(os.path.join(RUNTIME, "ready.json"), {
    "pid": os.getpid(), "session": SESSION, "ready_at": time.time(),
    "artifact": ARTIFACT})
bpy.app.timers.register(_poll, first_interval=0.1, persistent=True)
'''


